/** Todas las pasivas llevan un destello en una esquina libre: brillan en el inventario y en la tienda. */
const SPARKLE_SPOTS: [number, number][] = [[13, 2], [2, 2], [13, 13], [2, 13], [13, 8], [2, 8]];
function sparkle(rows: string[]): string[] {
  const grid = rows.map((r) => r.split(''));
  for (const [cx, cy] of SPARKLE_SPOTS) {
    const cells: [number, number, string][] = [[cx, cy, 'w'], [cx - 1, cy, 'h'], [cx + 1, cy, 'h'], [cx, cy - 1, 'h'], [cx, cy + 1, 'h']];
    // Solo si el hueco (con un píxel de margen) está vacío: nunca tapa el dibujo.
    const free = cells.every(([x, y]) => grid[y]?.[x] === '.') && grid[cy - 1]?.[cx - 1] === '.' && grid[cy + 1]?.[cx + 1] === '.';
    if (!free) continue;
    for (const [x, y, c] of cells) grid[y][x] = c;
    break;
  }
  return grid.map((r) => r.join(''));
}
for (const name of Object.keys(ART)) if (name.startsWith('p_')) ART[name] = sparkle(ART[name]);
